import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {pathToFileURL} from 'node:url';
import ts from 'typescript';
const source = ts.transpileModule(fs.readFileSync(new URL('../src/api.ts', import.meta.url),'utf8'),{compilerOptions:{module:ts.ModuleKind.ES2022,target:ts.ScriptTarget.ES2022}}).outputText;
const tmp=fs.mkdtempSync(path.join(os.tmpdir(),'control-api-test-'));
const modulePath=path.join(tmp,'api.mjs');fs.writeFileSync(modulePath,source);
const {ControlAPI}=await import(pathToFileURL(modulePath));
let expired=false;
const calls=[];
globalThis.fetch=async(url,init)=>{calls.push({url,init});return new Response(JSON.stringify({}),{status:200})};
const api=new ControlAPI('https://control.example',{kind:'web',csrfToken:'test-csrf',onExpired:()=>{expired=true}});
await api.bootstrap();await api.submitJob({},'stable-key');
assert.equal(calls[0].init.credentials,'same-origin');assert.equal(calls[0].init.headers.has('Authorization'),false);assert.equal(calls[1].init.headers.get('X-CSRF-Token'),'test-csrf');assert.equal(calls[1].init.headers.get('Idempotency-Key'),'stable-key');
globalThis.fetch=async()=>new Response('{}',{status:401});await assert.rejects(()=>api.bootstrap());assert.equal(expired,true);
console.log('Web API Cookie, CSRF, idempotency and expiry checks passed');
let nativeExpired=0;
const native=new ControlAPI('https://native.example',{kind:'native',token:'native-secret',onExpired:()=>nativeExpired++});
const controller=new AbortController();
globalThis.fetch=async(url,init)=>{assert.equal(init.headers.get('Authorization'),'Bearer native-secret');assert.equal(init.redirect,'error');assert.equal(init.credentials,'omit');assert.equal(init.signal,controller.signal);return new Response('{}',{status:401});};
await assert.rejects(()=>native.bootstrap(controller.signal));assert.equal(nativeExpired,1);
let afterRevocation=0;globalThis.fetch=async()=>{afterRevocation++;return new Response('{}')};
await assert.rejects(()=>native.bootstrap());assert.equal(afterRevocation,0);
console.log('Native authentication expiry stops later requests; redirect and abort boundaries passed');
const lifetime=new AbortController();let lifetimeCalls=0;
const scoped=new ControlAPI('https://scoped.example',{kind:'native',token:'key',onExpired(){}},lifetime.signal);
globalThis.fetch=async(_,init)=>{lifetimeCalls++;assert.equal(init.signal,lifetime.signal);return new Response('{}');};
await scoped.bootstrap();lifetime.abort();await assert.rejects(()=>scoped.bootstrap(),{name:'AbortError'});assert.equal(lifetimeCalls,1);
console.log('Unmount lifetime signal prevents further authenticated requests');
